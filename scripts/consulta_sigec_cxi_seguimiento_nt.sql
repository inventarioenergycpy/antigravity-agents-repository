-- 5. Cruce Integral CX-IN vs NT por Diferentes Mecanismos de Asociación
CRUCE_CX_NT AS (
    SELECT
        cx.SRV_CODIGO,
        cx.CNT_NUMERO,
        cx.ORD_NUMERO_CX,
        cx.TRT_NUMERO_CX,
        cx.ESTADO_CX,
        cx.RESULTADO_CX,
        cx.FECHA_GEN_CX,
        cx.FECHA_FIN_CX,
        cx.DATOS_RESULTADOS_CX,
        
        -- Datos de la Orden NT Posterior
        nt.ORD_NUMERO_NT,
        nt.TRT_NUMERO_NT,
        nt.ESTADO_NT,
        nt.RESULTADO_NT,
        nt.FECHA_GEN_NT,
        nt.FECHA_FIN_NT,
        nt.DATOS_RESULTADOS_NT,
        nt.DATOS_ADICIONALES_NT,
        
        -- Tipo de Enlace Detectado
        CASE
            WHEN nt.TRT_NUMERO_NT = cx.TRT_NUMERO_CX THEN '1. ENLACE DIRECTO POR TRT_NUMERO'
            WHEN nt.TRT_NUMERO_ORIGEN_NT = cx.TRT_NUMERO_CX THEN '2. ENLACE POR TRT_NUMERO_ORIGEN'
            WHEN UPPER(nt.DATOS_ADICIONALES_NT) LIKE '%' || TO_CHAR(cx.ORD_NUMERO_CX) || '%' THEN '3. MENCION ORD_CX EN DATOS ADICIONALES NT'
            WHEN UPPER(nt.DATOS_RESULTADOS_NT) LIKE '%' || TO_CHAR(cx.ORD_NUMERO_CX) || '%' THEN '4. MENCION ORD_CX EN RESULTADOS NT'
            WHEN obs.TRT_NUMERO IS NOT NULL THEN '5. MENCION EN OBSERVACIONES_TRAMITE'
            WHEN nt.FECHA_GEN_NT >= NVL(cx.FECHA_FIN_CX, cx.FECHA_GEN_CX) THEN '6. NT POSTERIOR POR CRONOLOGIA DE SUMINISTRO'
            ELSE '7. SIN NT ASOCIADA POSTERIOR'
        END AS TIPO_ASOCIACION,
        
        obs.OTR_DETALLE AS OBSERVACION_TRAMITE_DETALLE,
        ROW_NUMBER() OVER (
            PARTITION BY cx.SRV_CODIGO, cx.CNT_NUMERO, cx.ORD_NUMERO_CX
            ORDER BY
                CASE
                    WHEN nt.TRT_NUMERO_NT = cx.TRT_NUMERO_CX THEN 1
                    WHEN nt.TRT_NUMERO_ORIGEN_NT = cx.TRT_NUMERO_CX THEN 2
                    WHEN UPPER(nt.DATOS_ADICIONALES_NT) LIKE '%' || TO_CHAR(cx.ORD_NUMERO_CX) || '%' THEN 3
                    WHEN UPPER(nt.DATOS_RESULTADOS_NT) LIKE '%' || TO_CHAR(cx.ORD_NUMERO_CX) || '%' THEN 4
                    WHEN obs.TRT_NUMERO IS NOT NULL THEN 5
                    WHEN nt.FECHA_GEN_NT >= NVL(cx.FECHA_FIN_CX, cx.FECHA_GEN_CX) THEN 6
                    ELSE 9
                END,
                nt.FECHA_GEN_NT ASC NULLS LAST
        ) AS RN_NT
    FROM ORDENATIVOS_CX_IN cx
    LEFT JOIN ORDENATIVOS_NT_UNIVERSO nt
      ON cx.SRV_CODIGO = nt.SRV_CODIGO
     AND cx.CNT_NUMERO = nt.CNT_NUMERO
     AND (
            nt.TRT_NUMERO_NT = cx.TRT_NUMERO_CX
         OR nt.TRT_NUMERO_ORIGEN_NT = cx.TRT_NUMERO_CX
         OR UPPER(nt.DATOS_ADICIONALES_NT) LIKE '%' || TO_CHAR(cx.ORD_NUMERO_CX) || '%'
         OR UPPER(nt.DATOS_RESULTADOS_NT) LIKE '%' || TO_CHAR(cx.ORD_NUMERO_CX) || '%'
         OR nt.FECHA_GEN_NT >= TRUNC(NVL(cx.FECHA_FIN_CX, cx.FECHA_GEN_CX))
     )
    LEFT JOIN OBSERVACIONES_ASOCIADAS obs
      ON (obs.TRT_NUMERO = cx.TRT_NUMERO_CX OR (nt.TRT_NUMERO_NT IS NOT NULL AND obs.TRT_NUMERO = nt.TRT_NUMERO_NT))
     AND (
            UPPER(obs.OTR_DETALLE) LIKE '%' || TO_CHAR(cx.ORD_NUMERO_CX) || '%'
         OR UPPER(obs.OTR_DETALLE) LIKE '%CX%IN%'
         OR UPPER(obs.OTR_DETALLE) LIKE '%PILAR%'
         OR UPPER(obs.OTR_DETALLE) LIKE '%NORMALIZ%'
     )
)

-- 6. Reporte Final Consolidado con Estado de Normalización
SELECT
    SRV_CODIGO                      AS SUMINISTRO,
    CNT_NUMERO                      AS CONTRATO,
    ORD_NUMERO_CX                   AS NUM_ORDEN_CX,
    TRT_NUMERO_CX                   AS TRAMITE_CX,
    ESTADO_CX                       AS ESTADO_CX,
    RESULTADO_CX                    AS RESULTADO_CX,
    TO_CHAR(FECHA_GEN_CX, 'YYYY-MM-DD')  AS FECHA_GEN_CX,
    TO_CHAR(FECHA_FIN_CX, 'YYYY-MM-DD')  AS FECHA_FIN_CX,
    DATOS_RESULTADOS_CX             AS MOTIVO_IN_CX,
    
    -- Situación de la Orden NT
    TIPO_ASOCIACION                 AS TIPO_ASOCIACION_NT,
    ORD_NUMERO_NT                   AS NUM_ORDEN_NT,
    TRT_NUMERO_NT                   AS TRAMITE_NT,
    ESTADO_NT                       AS ESTADO_NT,
    RESULTADO_NT                    AS RESULTADO_NT,
    TO_CHAR(FECHA_GEN_NT, 'YYYY-MM-DD')  AS FECHA_GEN_NT,
    TO_CHAR(FECHA_FIN_NT, 'YYYY-MM-DD')  AS FECHA_FIN_NT,
    
    -- Diagnóstico del Caso
    CASE
        WHEN ORD_NUMERO_NT IS NULL THEN '🔴 SIN ORDEN NT POSTERIOR GENERADA'
        WHEN ESTADO_NT = 'EJ' AND RESULTADO_NT = 'OK' THEN '🟢 NORMALIZADO - NT EJECUTADA EXITOSA'
        WHEN ESTADO_NT = 'EJ' AND RESULTADO_NT <> 'OK' THEN '🟠 NT EJECUTADA CON OBSERVACION / IN'
        WHEN ESTADO_NT IN ('PE', 'TR', 'AS') THEN '🟡 NT EN CURSO / PENDIENTE DE EJECUCION'
        WHEN ESTADO_NT = 'AN' THEN '⚪ NT ANULADA'
        ELSE '🔵 NT EN ESTADO: ' || ESTADO_NT
    END AS DIAGNOSTICO_SEGUIMIENTO,
    
    DATOS_RESULTADOS_NT             AS RESULTADOS_NT,
    DATOS_ADICIONALES_NT            AS ADICIONALES_NT,
    OBSERVACION_TRAMITE_DETALLE     AS OBSERVACION_TRAMITE
FROM CRUCE_CX_NT
WHERE RN_NT = 1
ORDER BY
    CASE WHEN ORD_NUMERO_NT IS NULL THEN 1 ELSE 2 END,
    FECHA_FIN_CX DESC NULLS LAST;