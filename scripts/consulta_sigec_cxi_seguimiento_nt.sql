ORDENATIVOS_CX_IN AS (
    SELECT /*+ INDEX(ord ORD_SRV_CNT_IDX) */
        ord.SRV_CODIGO,
        ord.CNT_NUMERO,
        ord.ORD_NUMERO             AS ORD_NUMERO_CX,
